"""Build the three deliverables of the Caduceus UI from one source (plugin/caduceus_governance/ui/src): the standalone page phones open, the Hermes dashboard tab bundle, and the
Hermes Desktop pane. Each host takes a single file with no build step, so the app is inlined into each. `tests/test_ui_build.py` fails when a generated file drifts.

  python3 scripts/build_ui.py            write the generated files
  python3 scripts/build_ui.py --check    exit 1 if any generated file differs from what the sources produce
"""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
PLUG = os.path.join(ROOT, "plugin", "caduceus_governance")
SRC = os.path.join(PLUG, "ui", "src")


def read(*p):
    with open(os.path.join(*p), "r", encoding="utf-8") as fh:
        return fh.read()


DASH_GLUE = '''(function () {
  "use strict";
  var SDK = window.__HERMES_PLUGIN_SDK__, React = SDK.React, ID = "caduceus-governance";
%(app)s
  function api(method, path, body) {
    var init = { method: method };
    if (body !== undefined) { init.headers = { "Content-Type": "application/json" }; init.body = JSON.stringify(body); }
    return SDK.fetchJSON("/api/plugins/" + ID + path, init);
  }
  function Page() {
    var ref = React.useRef(null);
    React.useEffect(function () {
      var app = CaduceusApp(ref.current, { env: "dashboard", api: api });
      return function () { app.destroy(); };
    }, []);
    return React.createElement("div", { ref: ref, className: "cad-host" });
  }
  window.__HERMES_PLUGINS__.register(ID, Page);
})();
'''

DESKTOP_GLUE = '''// Generated by scripts/build_ui.py from ui/src. Do not edit; edit the sources and rebuild.
// Caduceus governance: the review pane and a status-bar chip. This pane reviews; approving is signed on a phone or another browser (a key on the agent's own machine proves little).
import { useQuery } from '@hermes/plugin-sdk'
import { jsx, jsxs } from 'react/jsx-runtime'
import { useEffect, useRef } from 'react'

%(app)s
const CSS = %(css)s

function Pane({ ctx }) {
  const ref = useRef(null)
  useEffect(() => {
    const app = CaduceusApp(ref.current, {
      env: 'desktop',
      canSign: false,
      api: (method, path, body) => ctx.rest(path, method === 'GET' ? undefined : { method, body }),
      store: { get: (k) => ctx.storage.get(k, null), set: (k, v) => ctx.storage.set(k, v) },
      copy: (text) => ctx.os.writeClipboard(text),
      notify: (title, body) => ctx.os.notify({ title, body }),
      setInterval: (fn, ms) => ctx.setInterval(fn, ms)
    })
    return () => app.destroy()
  }, [])
  return jsxs('div', { className: 'cad-wrap', children: [jsx('style', { children: CSS }), jsx('div', { ref, className: 'cad-host' })] })
}

function Chip({ ctx }) {
  const { data } = useQuery({ queryKey: [ctx.source, 'status'], queryFn: () => ctx.rest('/status'), refetchInterval: 8000 })
  const n = data && data.surfaces ? Object.values(data.surfaces).reduce((a, s) => a + ((s && s.held_effects) || []).length, 0) : 0
  return jsx('span', { className: 'px-1.5 text-[0.6875rem] text-(--ui-text-tertiary)', title: 'Caduceus: changes waiting at the gate', children: 'caduceus ' + (n ? n + ' held' : 'ok') })
}

export default {
  id: 'caduceus-governance',
  name: 'Caduceus governance',
  register(ctx) {
    ctx.register({ id: 'pane', area: 'panes', title: 'caduceus', data: { placement: 'right', width: '440px' }, render: () => jsx(Pane, { ctx }) })
    ctx.register({ id: 'chip', area: 'statusBar.right', order: 120, render: () => jsx(Chip, { ctx }) })
  }
}
'''


def outputs():
    css, js, shell = read(SRC, "app.css"), read(SRC, "app.js"), read(SRC, "shell.html")
    for bad in ("</" + "script", "<" + "script", "{{"):
        assert bad not in js and bad not in css, "source contains %r" % bad
    return {
        os.path.join(PLUG, "ui", "index.html"): shell.replace("{{CSS}}", css).replace("{{JS}}", js),
        os.path.join(PLUG, "dashboard", "dist", "index.js"): DASH_GLUE % {"app": js},
        os.path.join(PLUG, "dashboard", "dist", "style.css"): css,
        os.path.join(PLUG, "desktop", "plugin.js"): DESKTOP_GLUE % {"app": js, "css": json.dumps(css)},
    }


def main():
    out = outputs()
    if "--check" in sys.argv:
        for path, text in out.items():
            try:
                if read(path) != text:
                    print("out of date:", os.path.relpath(path, ROOT))
                    sys.exit(1)
            except OSError:
                print("missing:", os.path.relpath(path, ROOT))
                sys.exit(1)
        return
    for path, text in out.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote", os.path.relpath(path, ROOT), len(text))


if __name__ == "__main__":
    main()
