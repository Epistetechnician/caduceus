"""Emit an NVIDIA OpenShell sandbox policy that makes the Caduceus broker the only writer of the skills tree (PRD R11).

Verified against NVIDIA's published policy pages (docs.nvidia.com/openshell, 2026-11-04): a policy file sets `version: 1` and has top-level sections
`filesystem_policy`, `landlock`, `process`, `network_policies`, `network_middlewares`; the default policy leaves the working directory read-write and /tmp read-write.
NOT verified: the key names under `filesystem_policy` (the pages do not show them). The keys below are this module's best reading and MUST be checked with
`openshell policy` against a real sandbox before anyone relies on them. This module never runs OpenShell and makes no claim that the emitted file is accepted.

Effect when it is accepted: the agent process cannot write the skills tree at the OS level, so out-of-band writers and the mutation window disappear instead of being
detected and reverted. `skill_manage` writes then fail inside that sandbox by design; admitted changes arrive through the broker (`caduceus apply`), which runs outside it.
"""

from __future__ import annotations

import os

HEADER = """# Generated by `caduceus openshell-policy`. UNVERIFIED filesystem_policy key names: check with `openshell policy` before use.
# Effect: the agent sandbox may read the skills tree but not write it; the Caduceus broker (outside the sandbox) is the only writer.
"""


def _q(path: str) -> str:
    if any(c in path for c in "\n\r\"'\\") or not os.path.isabs(path):
        raise ValueError("skills root must be an absolute path without quotes or newlines")
    return '"%s"' % path


def render(skills_root: str, caduceus_dir: str) -> str:
    return (HEADER + "version: 1\n"
            "filesystem_policy:\n"
            "  read_only:\n"
            "    - %s\n"
            "  read_write:\n"
            "    - %s\n"
            "    - \"/tmp\"\n"
            "landlock:\n"
            "  compatibility: best_effort\n" % (_q(skills_root), _q(caduceus_dir)))
