"""Emit an NVIDIA OpenShell sandbox policy that makes the Caduceus broker the only writer of the skills tree (PRD R11).

Schema verified 2026-11-04 against NVIDIA's "Policy Schema Reference" (docs.nvidia.com/openshell/latest/how-it-works/policies/schema.md): a policy sets `version: 1`;
`filesystem_policy` has `include_workdir` (bool, default false once the section is present), `read_only` and `read_write` (absolute paths, no `..`, at most 256, `read_write`
may not contain `/`); unlisted paths are inaccessible; `landlock.compatibility` is `best_effort` (silently runs WITHOUT the filesystem rules if they cannot be applied) or
`hard_requirement` (the sandbox fails to start). `filesystem_policy` and `landlock` are startup fields. This module therefore emits `hard_requirement`: a guarantee that can
silently vanish is not one.

Landlock rules are additive, so a subdirectory cannot be made read-only inside a read-write parent. When a Hermes home is given, every existing top-level entry of it except
`skills` is listed read-write individually; an entry created later is not writable until the policy is regenerated.

Never run against a real OpenShell sandbox by this repository: the emitted file is checked against the documented schema, not accepted by the product.
Effect when accepted: the agent cannot write the skills tree at the OS level, so out-of-band writers and the mutation window disappear instead of being detected and
reverted. `skill_manage` writes then fail inside that sandbox by design; admitted changes arrive through the broker (`caduceus apply`), which runs outside it.
"""

from __future__ import annotations

import os
from typing import List, Optional

SYSTEM_READ = ("/usr", "/lib", "/lib64", "/bin", "/sbin", "/etc", "/opt", "/proc", "/dev")
MAX_PATHS = 256
HEADER = """# Generated by `caduceus openshell-policy`. Schema: docs.nvidia.com/openshell policies/schema.md (verified 2026-11-04). Not accepted by a real sandbox by this repository.
# Effect: the agent sandbox may read the skills tree but not write it; the Caduceus broker (outside the sandbox) is the only writer.
"""


def _check(path: str) -> str:
    if not os.path.isabs(path) or ".." in path.split("/") or len(path.encode()) > 4096 or any(c in path for c in "\n\r\"'\\:#[]{},") or path == "/":
        raise ValueError("path must be absolute, without '..', '/' alone or YAML-significant characters: %r" % path)
    return path


def render(skills_root: str, caduceus_dir: str, hermes_home: Optional[str] = None, extra_ro: tuple = ()) -> str:
    skills = os.path.normpath(_check(skills_root))  # validate the raw text first: normpath would hide a '..'
    cad = os.path.normpath(_check(caduceus_dir))
    ro: List[str] = [p for p in SYSTEM_READ if os.path.exists(p)] + [skills] + [_check(p) for p in extra_ro]
    rw: List[str] = ["/tmp", cad]
    if hermes_home:
        home = os.path.normpath(_check(hermes_home))
        for name in sorted(os.listdir(home)) if os.path.isdir(home) else []:
            p = os.path.join(home, name)
            if p not in (skills, cad):
                rw.append(_check(p))
        if home not in ro:
            ro.append(home)  # the home directory itself is listable; its entries are covered individually above
    rw = list(dict.fromkeys(rw))
    ro = [p for p in dict.fromkeys(ro) if p not in rw]
    if len(ro) > MAX_PATHS or len(rw) > MAX_PATHS:
        raise ValueError("OpenShell allows at most %d paths per list; list fewer Hermes home entries" % MAX_PATHS)
    lines = [HEADER + "version: 1", "filesystem_policy:", "  include_workdir: false", "  read_only:"]
    lines += ["    - %s" % p for p in ro] + ["  read_write:"] + ["    - %s" % p for p in rw]
    lines += ["landlock:", "  compatibility: hard_requirement", ""]
    return "\n".join(lines)
